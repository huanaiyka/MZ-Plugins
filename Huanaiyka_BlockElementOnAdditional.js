/*:
 * @target MZ
 * @plugindesc 屏蔽普通攻击的指定属性
 * @author 幻爱
 * @url https://github.com/huanaiyka/MZ-Plugins
 * @help
 * ============================================================================
 * 插件说明
 * ============================================================================
 * 当动作（技能/普通攻击）拥有追加属性时，自动移除参数中指定的属性，
 * 避免多属性共存，实现“火属性覆盖一般属性”之类的效果。
 *
 * 制作目的：使用DarkPlasma_MultiElementAction.js给普通攻击追加“一般”属性后，
 *           当武器为普通攻击赋予“火”属性时，去除原有的“一般”属性。
 * ============================================================================
 * 使用方法
 * ============================================================================
 * 1. 将本插件保存为 BlockElementOnAdditional.js，放入 js/plugins/ 文件夹。
 * 2. 在插件管理器中启用本插件。
 * 3. 在插件参数中设置“要屏蔽的属性ID”。
 *
 * ============================================================================
 * 属性ID对照
 * ============================================================================
 * 打开数据库 → “类型” → “属性”，列表第一项的ID为 0，依次递增。
 * 例如：
 *   草       → 0
 *   水       → 1
 *   火       → 2
 *
 * 若想屏蔽“草”，参数填 0。
 *
 * ============================================================================
 * 注意事项
 * ============================================================================
 * · 本插件只负责“移除”，不负责“追加”。
 *   追加属性请使用其他插件（如 DarkPlasma_MultiElementAction.js）。
 * · 加载顺序：追加属性的插件在前，本插件在后。
 * · 仅当动作拥有多个属性时才会移除指定属性；
 *   纯普通攻击（只有“一般”一个属性）不受影响。
 *
 * ============================================================================
 *
 * @param blockElementId
 * @text 要屏蔽的属性ID
 * @type number
 * @min 0
 * @default 1
 * @desc 填写要屏蔽的属性ID（在数据库“类型”→“属性”中查看，第一项从0开始）。
 */

(() => {
    const pluginName = "BlockElementOnAdditional";
    const params = PluginManager.parameters(pluginName);
    const blockElementId = Number(params["blockElementId"] || 1);

    const _Game_Action_elements = Game_Action.prototype.elements;
    Game_Action.prototype.elements = function() {
        const elements = _Game_Action_elements.call(this);
        // 仅当存在追加属性（元素数量 > 1）时，移除指定属性
        if (elements.length > 1) {
            return elements.filter(e => e !== blockElementId);
        }
        return elements;
    };
})();