/*:
 * @target MZ
 * @plugindesc 提供额外装备角色许可机制
 * @author 幻爱
 * @url https://github.com/huanaiyka/MZ-Plugins
 * @help
 * 
============================================================================
 * 简介
 * ============================================================================
 * 本插件通过备注标签灵活控制武器/防具的装备权限。
 * 支持全装备、禁止、专属、额外允许四种标签，并按优先级处理，便于管理复杂限制。
 * 
============================================================================
 * 标签用法说明
 * ============================================================================
 *
 * 本插件对「武器」和「防具」均有效，只要在对应物品的备注栏中写入标签即可。
 *
 * 1. 【全装备】<EquipAll>
 *    - 作用：使装备无视任何限制，所有角色均可装备（最高优先级）。
 *    - 示例：<EquipAll> → 所有角色都能装备该物品，忽略禁止/专属等其他所有标签及原有规则。
 *
 * 2. 【禁止】<BanEquipActor: id>
 *    - 作用：禁止指定角色装备。
 *    - 示例：<BanEquipActor: 3>    → 3号角色无法装备。
 *            <BanEquipActor: 1,5>  → 1号和5号角色无法装备。
 * 
 * 3. 【专属】<EquipOnlyActor: id> 
 *    - 作用：只有指定角色能装备（完全覆盖原有限制）。
 *    - 优先级次于禁止标签。
 *    - 示例：<EquipOnlyActor: 3>    → 只有3号角色可装备。
 *            <EquipOnlyActor: 1,3,5> → 只有1、3、5号角色可装备。
 * 
 * 4. 【额外通道】<AddEquipActor: id>
 *    - 作用：在游戏原有规则基础上，额外允许指定角色装备。
 *    - 优先级最低（但高于原生规则）。
 *    - 示例：<AddEquipActor: 3>    → 额外允许3号角色装备。
 *            <AddEquipActor: 2,4>  → 额外允许2号和4号角色装备。
 * 
 * ============================================================================
 * 优先级顺序（从高到低）
 * ============================================================================
 * ① <EquipAll>           —— 无视一切，全员可装备
 * ② <BanEquipActor>      —— 禁止特定角色
 * ③ <EquipOnlyActor>     —— 仅限特定角色
 * ④ <AddEquipActor>      —— 额外允许特定角色
 * ⑤ 游戏原生规则          —— 职业/装备类型等限制
 *
 * 注意：若存在 <EquipAll>，则②③④⑤全部无效，所有角色均可装备。
 *
 * ============================================================================
 * 使用示例
 * ============================================================================
 * 
 * 【示例1】让「万能钥匙」无视任何限制，所有人可装备
 *   - 在物品备注中写：<EquipAll>
 *   - 结果：任何角色都能装备，无论职业、类型、其他标签如何。
 * 
 * 【示例2】禁止战士「格鲁」(ID=2) 装备「诅咒大剑」
 *   - 在武器备注中写：<BanEquipActor: 2>
 *   - 结果：除格鲁外其他战士可装备，格鲁不能装备。
 * 
 * 【示例3】只有法师「爱丽丝」(ID=3) 能装备「魔法水晶杖」
 *   - 在武器备注中写：<EquipOnlyActor: 3>
 *   - 结果：无论原本谁能装备，现在只有爱丽丝可装备。
 * 
 * 【示例4】额外允许法师「爱丽丝」(ID=3) 装备「魔法剑」
 *   - 魔法剑原本只有战士能装备。
 *   - 在武器备注中写：<AddEquipActor: 3>
 *   - 结果：战士照常可装备，爱丽丝（法师）也可装备。
 * 
 * 【示例5】组合使用：禁止「格鲁」(2)，但额外允许「爱丽丝」(3)
 *   - 在武器备注中写：
 *        <BanEquipActor: 2>
 *        <AddEquipActor: 3>
 *   - 结果：格鲁不能装备；爱丽丝可装备（即使原规则不允许）；
 *          其他角色按原规则判定。
 * 
 * 【示例6】优先级验证：<EquipAll> 覆盖禁止
 *   - 同时写 <EquipAll> 和 <BanEquipActor: 3> → 3号角色仍然可以装备。
 * 
 * ============================================================================
 * 注意事项
 * ============================================================================
 * - 角色ID为数据库「角色」页面的编号（1开始）。
 * - 标签不区分大小写，但建议按示例书写。
 * - 如果没有任何标签，则完全遵循游戏默认规则。
 * - <EquipAll> 标签不带参数，直接写入即可生效。
 */

(function() {
    'use strict';

    const _Game_Actor_canEquip = Game_Actor.prototype.canEquip;

    Game_Actor.prototype.canEquip = function(item) {
        if (!item) return false;

        const note = item.note || "";

        // ★ 最高优先级：全装备标签（无视所有限制）
        if (/<EquipAll>/i.test(note)) {
            return true;  // 所有角色均可装备，不再进行任何其他判断
        }

        // 1. 禁止标签
        let matchBan = note.match(/<BanEquipActor:\s*([\d,\s]+)>/i);
        if (matchBan) {
            const banIds = matchBan[1].split(',').map(s => parseInt(s.trim(), 10));
            if (banIds.includes(this.actorId())) {
                return false;  // 被禁止，直接不允许
            }
        }

        // 2. 全局专属标签
        let matchOnly = note.match(/<EquipOnlyActor:\s*([\d,\s]+)>/i);
        if (matchOnly) {
            const onlyIds = matchOnly[1].split(',').map(s => parseInt(s.trim(), 10));
            // 只有在专属列表中的角色才允许装备
            return onlyIds.includes(this.actorId());
        }

        // 3. 额外通道标签
        let matchAdd = note.match(/<AddEquipActor:\s*([\d,\s]+)>/i);
        if (matchAdd) {
            const addIds = matchAdd[1].split(',').map(s => parseInt(s.trim(), 10));
            if (addIds.includes(this.actorId())) {
                return true;  // 被额外允许，直接通过
            }
        }

        // 4. 无特殊标签或未命中，走原有规则
        return _Game_Actor_canEquip.call(this, item);
    };
})();