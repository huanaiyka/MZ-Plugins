/*:
 * @target MZ
 * @plugindesc 隐藏主菜单中的“选项”命令
 * @author 幻爱
 * @url https://github.com/huanaiyka/MZ-Plugins
 *
 * @help
* 开启后，玩家在游戏中按 ESC 打开的菜单里不会出现“选项”按钮。
 * 但游戏刚开始的标题画面（主页面）中的“选项”会完好保留，方便玩家调音量或按键。
 * * 无需任何后续配置，直接启用即可生效。
 */

(() => {
    // 仅仅覆写游戏内菜单的选项添加方法，将其变为空白
    Window_MenuCommand.prototype.addOptionsCommand = function() {
        // 这里不执行任何操作，因此游戏内菜单不会渲染“选项”
    };
})();